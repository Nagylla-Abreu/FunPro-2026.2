print("\nPrograma para Gerar uma Sequência")
M = int(input("Digite o Valor inical da sequência de M: "))
N = int(input("Digite o Valor final da sequência N: "))

print("\nUFC - Programação")
print("Programa para Gerar uma Sequência")
print("Sequência:")
for i in range(M, N+1):
    print(i, end=" ")

print(f"\n\nValor de M = {M}")
print(f"Valor final de N = {N}")
print("\nFim de Trabalho")
